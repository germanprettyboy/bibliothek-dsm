test.describe("Italian category names", () => {
  test("missing names entered, published with books.js; without an import the date stays", async ({ page }) => {
    await withLibrary(page, LIB);
    await unlock(page);
    await expect(page.locator("#current #cov")).toBeVisible();
    await expect(page.locator("#dl")).toHaveCount(0);
    const row = page.locator('#cat-it [data-cat="Unbekannte Kategorie XY"]');
    await row.locator("input").fill("Categoria sconosciuta XY");
    await expect(page.locator("#r-again")).toBeVisible();
    const d = evaluate(await save(page, "#dl"), "DSM_LIBRARY");
    expect(d.updated).toBe("2026-09-01");
    expect(d.catIt).toEqual({ "Unbekannte Kategorie XY": "Categoria sconosciuta XY" });
    expect(d.books).toEqual(LIB.books);
    expect(d.history).toEqual(LIB.history);
    await expect(page.locator("#r-again")).toBeVisible(); // the card stays with its message
  });

  test("the list shows the name in Italian", async ({ page }) => {
    await page.addInitScript(() => localStorage.setItem("dsm-lang", "it"));
    await withLibrary(page, { ...LIB, catIt: { "Unbekannte Kategorie XY": "Categoria sconosciuta XY" } });
    await open(page);
    await page.locator("#list .row", { hasText: "Krabat" }).click();
    await expect(page.locator("#d-dl")).toContainText("Categoria sconosciuta XY");
  });
});

test.describe("hiding a wrong cover", () => {
  test("search, look at the cover, hide it, publish; showing it again", async ({ page, net }) => {
    net.image = url => url.includes("cover.ekz.de/" + ISBN);
    await withLibrary(page, LIB);
    await unlock(page);
    await page.fill("#nc-q", "krabat");
    await page.locator("#nc-res button").click();
    await expect(page.locator("#nc-sel img")).toHaveAttribute("src", `https://cover.ekz.de/${ISBN}.jpg`);
    await expect(page.locator("#nc-state")).toHaveText("Quelle: ekz-Bibliotheksservice");
    await page.click("#nc-hide");
    await expect(page.locator("#nc-sel img")).toHaveCount(0);
    await expect(page.locator(`#nc-list [data-isbn="${ISBN}"]`)).toContainText("Krabat");
    const d = evaluate(await save(page, "#dl"), "DSM_LIBRARY");
    expect(d.noCover).toEqual([ISBN]);
    await page.click("#nc-unhide");
    await expect(page.locator("#nocover")).toContainText("Keine Cover ausgeblendet.");
    await expect(page.locator("#dl")).toBeVisible();
  });

  test("the list shows the placeholder and asks no cover service", async ({ page, net }) => {
    net.image = () => true;
    await withLibrary(page, { ...LIB, noCover: [ISBN] });
    await open(page);
    await page.locator("#list .row", { hasText: "Krabat" }).click();
    await expect(page.locator("#d-cover .ph b")).toHaveText("Krabat");
    await expect(page.locator("#d-cover")).not.toHaveClass(/loading/);
    await expect(page.locator("#d-cover img")).toHaveCount(0);
    expect(net.requests.filter(u => u.includes(ISBN))).toEqual([]);
  });
});

