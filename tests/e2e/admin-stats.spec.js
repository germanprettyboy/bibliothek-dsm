/*
 * Admin page, tab "Statistik" (tools/source/admin/stats.jsx + charts.jsx): charts from the published list before an
 * import (key figures, covers, age, categories, history) plus a hint; after the import also the maintenance charts.
 * A bar of the problems chart opens tab "Pflege"; every chart has a table twin; no horizontal scrolling on the phone.
 */
const { test, expect, settled } = require("./helpers.js");
const { adminSetup, unlock, importTest, tab } = require("./admin-helpers.js");

adminSetup();

// Small published list: 4 books, 2 with ISBN, 3 categories, years 1929/1973/1981/2010, two publications
const LIB = {
  updated: "2026-09-01", count: 4,
  coverage: { updated: "2026-09-01", books: 4, isbn: 2 },
  history: [{ updated: "2026-06-01", books: 3, isbn: 1 }, { updated: "2026-09-01", books: 4, isbn: 2 }],
  books: [
    { t: "Krabat", a: ["Otfried Preußler"], i: ["9783522202107"], y: "1981", c: "Jugendbuch" },
    { t: "Momo", a: ["Michael Ende"], y: "1973", c: "Jugendbuch" },
    { t: "Tschick", a: ["Wolfgang Herrndorf"], i: ["9783499256356"], y: "2010", c: "Roman" },
    { t: "Emil und die Detektive", a: ["Erich Kästner"], y: "1929", c: "Klassiker" },
  ],
};
const script = d => "/* Book list of the library of the Deutsche Schule Mailand. Generated by admin.html – do not edit by hand. */\nwindow.DSM_LIBRARY = " + JSON.stringify(d) + ";\n";
const withLibrary = (page, d) => page.route("**/books.js", r => r.fulfill({ body: script(d), contentType: "text/javascript" }));
const chart = (page, name) => page.locator(`#tab-stats [data-chart="${name}"]`);

test.describe("tab Statistik", () => {
  test("before an import: charts of the published list, key figure = list count, hint leads to the catalog", { tag: "@smoke" }, async ({ page }) => {
    await withLibrary(page, LIB);
    await unlock(page);
    await tab(page, "stats");
    expect(await page.locator("#tab-stats [data-chart]").count()).toBeGreaterThanOrEqual(3);
    for (const name of ["kpi", "coverage", "age", "categories", "history"]) await expect(chart(page, name)).toBeVisible();
    await expect(chart(page, "kpi").locator('[data-kpi="books"] .st-kpi-value')).toHaveText(String(LIB.books.length));
    await expect(chart(page, "kpi").locator('[data-kpi="isbn"] .st-kpi-value')).toHaveText("50 %");
    // maintenance charts only after an import
    await expect(chart(page, "problems")).toHaveCount(0);
    await expect(chart(page, "acquisitions")).toHaveCount(0);
    await expect(chart(page, "age")).toContainText("Median 1973");
    await expect(page.locator("#st-hint")).toContainText("Nach dem Einlesen der WinBIAP-Datei");
    await page.click("#st-to-catalog");
    await expect(page.locator("#tab-catalog")).toBeVisible();
  });

  test("table twin, bin toggle and the tooltip on keyboard focus", async ({ page }) => {
    await withLibrary(page, LIB);
    await unlock(page);
    await tab(page, "stats");
    const age = chart(page, "age");
    const toggle = age.locator("[data-table-toggle]");
    await expect(toggle).toHaveAttribute("aria-expanded", "false");
    await toggle.click();
    await expect(toggle).toHaveAttribute("aria-expanded", "true");
    // decades 1920 … 2010
    await expect(age.locator("table tbody tr")).toHaveCount(10);
    await expect(age.locator("table tbody tr").first()).toContainText("1920–1929");
    await age.locator('#st-age-bin [data-v="5"]').click();
    await expect(age.locator("table tbody tr")).toHaveCount(18);
    await settled(page);
    await age.locator(".st-hit").first().focus();
    await expect(age.locator(".st-tip")).toContainText("1925");
    // coverage without a cover check: with ISBN (not checked) and without ISBN
    await expect(chart(page, "coverage").locator('li[data-part="open"]')).toContainText("2");
    await expect(chart(page, "coverage").locator('li[data-part="noisbn"]')).toContainText("2");
  });

  test("after the import: error and accession charts; a bar of the problems chart opens tab Pflege", async ({ page }) => {
    await unlock(page);
    await importTest(page);
    await tab(page, "stats");
    await expect(page.locator("#st-hint")).toHaveCount(0);
    for (const name of ["kpi", "problems", "rate", "locations", "acquisitions"]) await expect(chart(page, name)).toBeVisible();
    await expect(chart(page, "kpi").locator('[data-kpi="copies"] .st-kpi-value')).toHaveText("10");
    await expect(chart(page, "problems").locator('[data-bar="isbnNone"]')).toContainText("5");
    await expect(chart(page, "problems").locator('[data-bar="isbnBad"]')).toContainText("1");
    await expect(page.locator("#tab-stats")).not.toContainText("Musterfrau");
    await chart(page, "problems").locator('[data-bar="isbnBad"] button').click();
    await expect(page.locator("#tab-care")).toBeVisible();
  });

  test("phone: no horizontal scrolling", async ({ page }) => {
    await page.setViewportSize({ width: 375, height: 800 });
    await unlock(page);
    await importTest(page);
    await tab(page, "stats");
    await expect(chart(page, "problems")).toBeVisible();
    await settled(page);
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375);
  });
});
