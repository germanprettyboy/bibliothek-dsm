/*
 * One-time migration of the data files from the German format (until October 2026) to the English one.
 *
 *   node tools/migrate-data.mjs [folder]     default folder: website/
 *
 * Reads books.js, empfehlungen.js (or recommendations.js) and info.js in the old format and writes
 * books.js, recommendations.js and info.js in the new format into the same folder (empfehlungen.js is removed).
 * Files that are already in the new format are left alone. Use it for the copies from the webspace before uploading:
 * download books.js, empfehlungen.js and info.js via FTP into an empty folder, run this, upload the result.
 */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";

const HEAD = {
  books: "/* Book list of the library of the Deutsche Schule Mailand. Generated by admin.html – do not edit by hand. */\nwindow.DSM_LIBRARY = ",
  recs: "/* Book recommendations of the library of the Deutsche Schule Mailand. Maintained via admin.html – do not edit by hand. */\nwindow.DSM_RECOMMENDATIONS = ",
  info: "/* Opening hours, holidays and absences of the library of the Deutsche Schule Mailand. Maintained via admin.html – do not edit by hand. */\nwindow.DSM_INFO = ",
};
const GROUPS = { mittelstufe: "middle", oberstufe: "upper", "erw-roman": "adult-fiction", "erw-sach": "adult-nonfiction", "erw-bio": "adult-bio" };
const DAYS = { mo: "mon", di: "tue", mi: "wed", do: "thu", fr: "fri", sa: "sat", so: "sun" };

// Runs a data file in a sandbox and returns its window.DSM_… object
function load(file) {
  const window = {};
  vm.runInNewContext(fs.readFileSync(file, "utf8"), { window });
  return window;
}
const pick = (o, map) => Object.fromEntries(Object.entries(map).filter(([k]) => o[k] !== undefined).map(([k, n]) => [n, o[k]]));

export function migrateBooks(d) {
  if (d.books) return d;
  const out = pick(d, { stand: "updated", anzahl: "count" });
  const entry = e => pick(e, { stand: "updated", buecher: "books", isbn: "isbn", cover: "cover", ekz: "ekz", ol: "ol", gb: "gb", ohne: "none", geprueft: "checked", vollstaendig: "complete" });
  if (d.abdeckung) out.coverage = entry(d.abdeckung);
  if (d.verlauf) out.history = d.verlauf.map(entry);
  // t title, s subtitle, a authors, p publisher, y year, i ISBNs, c category, l locations (same order as before)
  out.books = (d.buecher || []).map(b => pick(b, { t: "t", u: "s", a: "a", v: "p", j: "y", i: "i", k: "c", s: "l" }));
  return out;
}
function round(r) {
  const out = pick(r, { stand: "updated", thema: "topic" });
  out.groups = Object.fromEntries(Object.entries(r.gruppen || {}).map(([g, l]) => [GROUPS[g] || g, l]));
  return out;
}
export function migrateRecs(d) {
  if (d.groups) return d;
  const out = round(d);
  if (d.archiv) out.archive = d.archiv.map(round);
  return out;
}
export function migrateInfo(d) {
  if (d.hours) return d;
  return {
    updated: d.stand,
    hours: Object.fromEntries(Object.entries(d.zeiten || {}).map(([k, v]) => [DAYS[k] || k, v])),
    notice: d.hinweis || { de: "", it: "" },
    closures: (d.schliessungen || []).map(c => ({ type: c.art === "abwesend" ? "absent" : "holiday", from: c.von, to: c.bis, de: c.de || "", it: c.it || "" })),
  };
}

// Same serialization as the admin page: books.js compact, the other two indented by one space
const write = (file, head, data, indent) => fs.writeFileSync(file, head + JSON.stringify(data, null, indent).replace(/</g, "\\u003c") + ";\n");

if (import.meta.url === `file://${process.argv[1]}`) {
  const dir = path.resolve(process.argv[2] || path.join(path.dirname(new URL(import.meta.url).pathname), "..", "website"));
  const f = n => path.join(dir, n);
  if (fs.existsSync(f("books.js"))) {
    const w = load(f("books.js"));
    if (w.DSM_BIBLIOTHEK) { write(f("books.js"), HEAD.books, migrateBooks(w.DSM_BIBLIOTHEK)); console.log("migrated: books.js"); }
  }
  const recsOld = fs.existsSync(f("empfehlungen.js")) ? f("empfehlungen.js") : fs.existsSync(f("recommendations.js")) ? f("recommendations.js") : null;
  if (recsOld) {
    const w = load(recsOld);
    const d = w.DSM_EMPFEHLUNGEN || w.DSM_RECOMMENDATIONS;
    if (d && !d.groups) {
      write(f("recommendations.js"), HEAD.recs, migrateRecs(d), 1);
      if (recsOld.endsWith("empfehlungen.js")) fs.unlinkSync(recsOld);
      console.log("migrated: empfehlungen.js → recommendations.js");
    }
  }
  if (fs.existsSync(f("info.js"))) {
    const d = load(f("info.js")).DSM_INFO;
    if (d && !d.hours) { write(f("info.js"), HEAD.info, migrateInfo(d), 1); console.log("migrated: info.js"); }
  }
}
