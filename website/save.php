<?php
/*
 * Publish directly: the admin page (admin.html) sends books.js, recommendations.js or info.js here,
 * the file is replaced in the website folder immediately. The website's only server file, no database, PHP 7.1+.
 *
 *   GET  save.php                 → {"dsm":"save","v":3,"ready":true|false,"reason"?}
 *   POST save.php?file=info.js    header X-DSM-Key, body = finished file → {"ok":true,…}
 *   GET  save.php?backups         header X-DSM-Key → {"ok":true,"backups":{"info.js":[{name,size,time}, newest first],…}}
 *   POST save.php?restore=<backup name>   header X-DSM-Key, no body → {"ok":true,"file":…}
 *
 * Protection: the key is derived from the admin password and lives only in the encrypted admin app
 * (assets/admin.enc.js). Only its SHA-256 is stored here (save-access.php, generated by tools/encrypt-admin.js).
 * Only the three file names are accepted, and only in exactly the format the admin page produces:
 * fixed header line, "window.DSM_… = ", one JSON object, ";" – foreign JavaScript code can't get through that way.
 * Before every write the old version moves to backup/ (the last 10 per file, locked for visitors via backup/.htaccess).
 * Restoring checks the backup like an upload and writes it like one (the current version becomes a backup first).
 */
declare(strict_types=1);
date_default_timezone_set('Europe/Rome'); // backup names in local time

const DSM_FILES = [
  'books.js' => ["/* Book list of the library of the Deutsche Schule Mailand. Generated by admin.html – do not edit by hand. */\nwindow.DSM_LIBRARY = ", 'books'],
  'recommendations.js' => ["/* Book recommendations of the library of the Deutsche Schule Mailand. Maintained via admin.html – do not edit by hand. */\nwindow.DSM_RECOMMENDATIONS = ", 'groups'],
  'info.js' => ["/* Opening hours, holidays and absences of the library of the Deutsche Schule Mailand. Maintained via admin.html – do not edit by hand. */\nwindow.DSM_INFO = ", 'hours'],
];
const DSM_MAX = 8 * 1024 * 1024;
const DSM_BACKUPS = 10;
// backup/.htaccess: the backups are only for restoring via FTP, Apache never serves them (2.4 / 2.2; other servers ignore it)
const DSM_BACKUP_DENY = "<IfModule mod_authz_core.c>\n  Require all denied\n</IfModule>\n<IfModule !mod_authz_core.c>\n  Order allow,deny\n  Deny from all\n</IfModule>\n";

// DSM_ACCESS_FILE and DSM_DATA_FOLDER are only set by the local development server (tools/local-router.php)
function dsm_access(string $folder): string {
  $file = defined('DSM_ACCESS_FILE') ? DSM_ACCESS_FILE : $folder . '/save-access.php';
  $hash = is_file($file) ? include $file : '';
  return is_string($hash) && preg_match('/^[0-9a-f]{64}$/', $hash) ? $hash : '';
}

// Format check of upload and restore alike: header line, one JSON object with the required field, ";\n".
// Returns [error response or null, data or null].
function dsm_check(string $file, $text): array {
  if (!is_string($text) || $text === '') return [[400, ['error' => 'empty']], null];
  if (strlen($text) > DSM_MAX) return [[413, ['error' => 'too-large']], null];
  list($head, $required) = DSM_FILES[$file];
  if (strncmp($text, $head, strlen($head)) !== 0 || substr($text, -2) !== ";\n") return [[422, ['error' => 'format']], null];
  $json = substr($text, strlen($head), -2);
  $data = $json !== '' && $json[0] === '{' ? json_decode($json, false, 64) : null;
  if (!is_object($data) || !isset($data->$required)) return [[422, ['error' => 'format']], null];
  return [null, $data];
}

// Backup names of one data file: info-20261022-143005.js (a second one in the same second: …143005b.js)
function dsm_backup_pattern(string $file): string {
  return '/^' . preg_quote(substr($file, 0, -3), '/') . '-(\d{4})(\d{2})(\d{2})-(\d{2})(\d{2})(\d{2})[a-z]?\.js$/D'; // D: no trailing newline
}

// Writes the finished text as the new version: old one to backup/ first, rotation, flock, atomic replacement.
// Returns null or an error response.
function dsm_write(string $folder, string $file, string $text): ?array {
  $backup = $folder . '/backup';
  if (!is_dir($backup) && !@mkdir($backup, 0755)) return [500, ['error' => 'not-writable']];
  if (!is_file($backup . '/.htaccess')) @file_put_contents($backup . '/.htaccess', DSM_BACKUP_DENY);
  $lock = @fopen($backup . '/.lock', 'c');
  if (!$lock || !flock($lock, LOCK_EX)) return [500, ['error' => 'lock']];
  try {
    $target = $folder . '/' . $file;
    $name = substr($file, 0, -3);
    if (is_file($target)) {
      // twice in the same second: append a letter (sorts after the first one), never overwrite anything
      $base = sprintf('%s/%s-%s', $backup, $name, date('Ymd-His'));
      $old = $base . '.js';
      for ($z = ord('b'); is_file($old) && $z <= ord('z'); $z++) $old = $base . chr($z) . '.js';
      copy($target, $old);
      $olds = glob($backup . '/' . $name . '-*.js') ?: [];
      sort($olds);
      foreach (array_slice($olds, 0, max(0, count($olds) - DSM_BACKUPS)) as $old) @unlink($old);
    }
    // write completely first, then replace in one step: visitors never see half a file
    $new = $folder . '/.' . $file . '.new';
    if (file_put_contents($new, $text) !== strlen($text) || !rename($new, $target)) {
      @unlink($new);
      return [500, ['error' => 'not-writable']];
    }
  } finally {
    flock($lock, LOCK_UN);
    fclose($lock);
  }
  return null;
}

// Returns [HTTP status, response]. $read fetches the body only after the key has been checked.
// $query = $_GET: ?backups (GET) lists the backups, ?restore=<backup name> (POST) restores one.
function dsm_save(string $method, string $file, string $key, callable $read, string $folder, array $query = []): array {
  $hash = dsm_access($folder);
  $list = $method === 'GET' && isset($query['backups']);
  if ($method === 'GET' && !$list) {
    if ($hash === '') return [200, ['ready' => false, 'reason' => 'access']];
    if (!is_writable($folder)) return [200, ['ready' => false, 'reason' => 'not-writable']];
    return [200, ['ready' => true]];
  }
  if ($method !== 'POST' && !$list) return [405, ['error' => 'method']];
  if ($hash === '') return [503, ['error' => 'access']];
  if (!hash_equals($hash, hash('sha256', $key))) return [403, ['error' => 'key']];

  if ($list) {
    $out = [];
    foreach (array_keys(DSM_FILES) as $f) {
      $found = [];
      foreach (glob($folder . '/backup/' . substr($f, 0, -3) . '-*.js') ?: [] as $path) {
        if (preg_match(dsm_backup_pattern($f), basename($path), $m) && is_file($path)) {
          $found[basename($path)] = ['name' => basename($path), 'size' => (int) filesize($path),
            'time' => sprintf('%s-%s-%sT%s:%s:%s', $m[1], $m[2], $m[3], $m[4], $m[5], $m[6])];
        }
      }
      krsort($found); // the letter of a second backup in the same second sorts after the first one
      $out[$f] = array_values($found);
    }
    return [200, ['ok' => true, 'backups' => $out]];
  }

  if (isset($query['restore'])) {
    $name = is_string($query['restore']) ? $query['restore'] : '';
    $file = '';
    foreach (array_keys(DSM_FILES) as $f) if (preg_match(dsm_backup_pattern($f), $name)) $file = $f;
    if ($file === '') return [400, ['error' => 'name']];
    $source = $folder . '/backup/' . $name;
    if (!is_file($source)) return [404, ['error' => 'missing']];
    $text = @file_get_contents($source, false, null, 0, DSM_MAX + 1);
    list($error) = dsm_check($file, $text === false ? '' : $text);
    if ($error) return $error;
    $error = dsm_write($folder, $file, $text);
    return $error ?: [200, ['ok' => true, 'file' => $file]];
  }

  if (!array_key_exists($file, DSM_FILES)) return [400, ['error' => 'file']];
  $text = $read();
  list($error, $data) = dsm_check($file, $text);
  if ($error) return $error;
  $error = dsm_write($folder, $file, $text);
  if ($error) return $error;
  return [200, ['ok' => true, 'file' => $file, 'bytes' => strlen($text), 'updated' => isset($data->updated) && is_scalar($data->updated) ? (string) $data->updated : '']];
}

if (!defined('DSM_SAVE_TEST')) {
  // PHP warnings only into the server log (npm run local: the terminal), never into the answer: printed before the JSON
  // they send the headers early (status always 200, text/html) and the admin page can only report "HTTP 200".
  // php-wasm and many webspaces display them by default; the buffer also swallows anything a host prints regardless.
  ini_set('display_errors', '0');
  ini_set('log_errors', '1');
  ob_start();
  list($status, $response) = dsm_save(
    (string) ($_SERVER['REQUEST_METHOD'] ?? ''),
    (string) ($_GET['file'] ?? ''),
    (string) ($_SERVER['HTTP_X_DSM_KEY'] ?? ''),
    function () { return file_get_contents('php://input', false, null, 0, DSM_MAX + 1); },
    defined('DSM_DATA_FOLDER') ? DSM_DATA_FOLDER : __DIR__,
    $_GET
  );
  if ($status === 403) sleep(1); // slow down guessing
  ob_end_clean();
  http_response_code($status);
  header('Content-Type: application/json; charset=utf-8');
  header('Cache-Control: no-store');
  header('X-Content-Type-Options: nosniff');
  echo json_encode(['dsm' => 'save', 'v' => 3] + $response, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
}
